#!/usr/bin/env python3
"""Deterministically bundle the canonical dashboard into the ESP32 sketch."""
import argparse
import gzip
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generate(check=False):
    source = (ROOT / "index.html").read_bytes()
    dashboard = ROOT / "dashboard.html"
    compressed = gzip.compress(source, compresslevel=9, mtime=0)
    rows = [", ".join(f"0x{value:02x}" for value in compressed[i:i + 16])
            for i in range(0, len(compressed), 16)]
    header = ("// Generated by tools/embed_dashboard.py; do not edit.\n"
              f"// HTML SHA256: {hashlib.sha256(source).hexdigest()}\n"
              "#pragma once\n#include <Arduino.h>\n"
              "static const uint8_t DASHBOARD_GZ[] PROGMEM = {\n  "
              + ",\n  ".join(rows)
              + "\n};\nconstexpr size_t DASHBOARD_GZ_LEN = sizeof(DASHBOARD_GZ);\n")
    target = ROOT / "firmware/LampuHiasPintar/dashboard.h"
    if check:
        assert dashboard.read_bytes() == source, "dashboard.html is stale"
        assert target.read_text() == header, "dashboard.h is stale; regenerate"
    else:
        dashboard.write_bytes(source)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(header)
    print(f"Dashboard: {len(source):,} bytes HTML → {len(compressed):,} bytes gzip")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    generate(parser.parse_args().check)
